"""App settings, read from environment / backend/.env."""
from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict

BASE_DIR = Path(__file__).resolve().parent.parent


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=BASE_DIR / ".env", extra="ignore")

    database_url: str = f"sqlite:///{BASE_DIR / 'data' / 'reportzene.db'}"
    web_dist: Path = BASE_DIR.parent / "web" / "dist"
    session_days: int = 30
    cors_origins: str = "http://localhost:5177"
    cookie_name: str = "rzn_session"
    cookie_secure: bool = False  # true behind HTTPS (Cloudflare tunnel)
    timezone: str = "Asia/Ho_Chi_Minh"
    secret_key: str = ""  # encrypts the tokens saved in Settings; generated by deploy.sh

    # "Sign in with POD" (SSO production.trackingis.info). Secret only in the launchd plist, never in git.
    pod_url: str = "https://production.trackingis.info"
    pod_app_key: str = ""
    pod_app_secret: str = ""
    pod_redirect_url: str = ""
    pod_timeout_seconds: float = 10.0
    # Comma list of emails let in on their first SSO sign-in; anyone else is created locked until an admin unlocks them
    pod_allowed_users: str = ""
    allow_password_login: bool = True  # break-glass email + password login for admins

    # trackingis API (internal /api/v2 routes, Bearer). The token is normally saved in Settings; env is a fallback.
    trackingis_url: str = "https://production.trackingis.info"
    trackingis_token: str = ""
    trackingis_timeout_seconds: float = 60.0
    default_teams: str = ""  # comma list of trackingis team ids the report starts with (ZenE teams); editable in Settings

    # Lark custom app that reads the team's report sheets (read-only); credentials normally saved in Settings
    lark_app_id: str = ""
    lark_app_secret: str = ""
    lark_base_url: str = "https://open.larksuite.com"
    sheet_sync_at: str = "10:00"  # every team sheet is read again daily at this time (HH:MM, app timezone); editable in Settings
    sheet_max_rows: int = 5000
    # Etsy › Plan: the plan-by-product block of a team sheet (sheet picked in Settings; column and count editable there)
    plan_start_column: int = 17  # column Q of the "KH theo Product" tab
    plan_products: int = 11

    # First admin, created on startup when the users table is empty
    bootstrap_email: str = ""
    bootstrap_password: str = ""
    bootstrap_name: str = "Admin"
    bootstrap_code: str = "ADMIN"

    @property
    def pod_enabled(self) -> bool:
        return bool(self.pod_app_key and self.pod_app_secret and self.pod_redirect_url)

    @property
    def allowed_emails(self) -> set[str]:
        return {e.strip().lower() for e in self.pod_allowed_users.split(",") if e.strip()}


settings = Settings()
